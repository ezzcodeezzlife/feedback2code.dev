import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "dotenv";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const isProd = process.argv.includes("--production");
const basename = isProd ? ".env.production" : ".env.development";
const envPath = path.join(root, basename);

const dir = path.join(root, "lib", "generated");
fs.mkdirSync(dir, { recursive: true });
const outPath = path.join(dir, "server-env.ts");

/**
 * Local: bake from gitignored `.env.*` so NextAuth/Prisma see secrets in the bundle.
 * Vercel/CI: those files are absent — rely on platform `process.env` (do not fail the build).
 */
if (!fs.existsSync(envPath)) {
  const stub = `/* eslint-disable -- generated by scripts/generate-server-env.mjs; do not edit */
import "server-only";

// No ${basename} on disk (e.g. Vercel). Runtime uses process.env from the host.
`;
  fs.writeFileSync(outPath, stub, "utf8");
  console.log(
    `generate-server-env: wrote stub lib/generated/server-env.ts (missing ${basename}; using process.env)`,
  );
  process.exit(0);
}

const parsed = parse(fs.readFileSync(envPath, "utf8"));
const lines = Object.entries(parsed).map(
  ([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`,
);

const out = `/* eslint-disable -- generated by scripts/generate-server-env.mjs; do not edit */
import "server-only";

const injected: Record<string, string> = {
${lines.join("\n")}
};

for (const [key, value] of Object.entries(injected)) {
  process.env[key] = value;
}
`;

fs.writeFileSync(outPath, out, "utf8");
console.log(`generate-server-env: wrote lib/generated/server-env.ts from ${basename}`);
